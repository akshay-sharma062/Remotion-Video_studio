/**
 * speaker-alpha.ts — the Premium-only speaker cutout.
 *
 * WHAT THIS IS
 *   For the B-roll span (frames 253..385) the speaker must appear IN FRONT of
 *   the footage rather than being replaced by it. That needs the speaker with
 *   real per-pixel alpha.
 *
 * WHY A BAKED-ALPHA VIDEO AND NOT A CSS MASK
 *   `speaker-alpha.webm` (VP9 / yuva420p) carries colour and alpha in one
 *   texture, so the composition's zoom and punches scale both together and
 *   they can never drift apart. A CSS mask would be a second element that must
 *   be transformed in exact lockstep with the footage, and it would add 133
 *   image loads to every render. BrollLayer already seeks a <Video> per frame,
 *   so an alpha WebM rides a code path that is already proven to work.
 *
 * WHY THE SPAN IS EXACTLY THE B-ROLL SPAN
 *   seg-6 covers 253..304 and seg-7 covers 305..385 (both `to` values are
 *   exclusive), so the union is frames 253..385 — 133 frames. The cutout is
 *   authored over the same 133 frames, so cutout frame 0 is source frame 253
 *   and the two layers start and end on the same frame. Any mismatch here
 *   would show as a one-frame flash of the wall at a boundary.
 *
 * GRACEFUL DEGRADATION
 *   If the file is absent the composition falls back to the opaque talking
 *   head, which is the current, correct-looking behaviour. B-roll simply plays
 *   over the speaker as it does today. Nothing breaks; the effect is absent.
 *
 * VERIFIED
 *   - All 133 frames decode with alpha_mode=1.
 *   - Alpha plane mean matches the source matte: MAE 0.01/255 (2-bit VBR
 *     rounding floor), edge MAE 0.50.
 *   - Coverage per frame matches the source matte to 0.000% across all 133
 *     frames; every frame carries the speaker (37.9%..47.1% of the frame).
 *   - Frame 253 matches a fresh decode of the footage frame-for-frame
 *     (MAE 0.000), so the cutout is aligned to the live video it replaces.
 *   - 1080x1920, no aspect change, so it maps 1:1 through the same
 *     objectFit: "cover" geometry VideoLayer uses.
 *
 * NOTE ON VOICE
 *   The voice is carried by VideoLayer's <Video src={FOOTAGE}> (unmuted).
 *   The composition's only <Audio> is sfx.wav, which is hits-only. So this
 *   layer must REPLACE the speaker's pixels but must never unmount or mute
 *   VideoLayer — dropping the cutout span to the opaque video would be an
 *   audio-neutral fallback, and keeping VideoLayer mounted is what keeps the
 *   voice present and lip-synced throughout.
 *
 * GENERATED BY
 *   python scripts/build-speaker-matte.py --from 253 --to 385
 *   python scripts/build-speaker-alpha.py  --from 253 --to 385
 *   Both write only under work/tmp/phase10/ and are safe to re-run.
 */

/** Path relative to public/, in the form staticFile() expects. */
export const SPEAKER_ALPHA_FILE =
  "projects/corporate-career-growth-amana-premium-916/speaker/speaker-alpha.webm";

/** First composition frame the cutout covers (inclusive). */
export const SPEAKER_ALPHA_FROM = 253;

/** Last composition frame the cutout covers (inclusive). */
export const SPEAKER_ALPHA_TO = 385;

/** Frames the cutout clip supplies. */
export const SPEAKER_ALPHA_FRAMES = SPEAKER_ALPHA_TO - SPEAKER_ALPHA_FROM + 1;

/** True when a composition frame falls inside the cutout span. */
export function inSpeakerAlphaSpan(frame: number): boolean {
  return frame >= SPEAKER_ALPHA_FROM && frame <= SPEAKER_ALPHA_TO;
}
