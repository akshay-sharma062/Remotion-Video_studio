// ─── Animated Kinetic Caption ───────────────────────────────────────────────
/**
 * Renders a kinetic headline from blueprint caption events.
 *
 * Features:
 * - Word-by-word entrance with stagger
 * - Per-word highlight with color and scale
 * - Exit animation
 * - Position within safe zones
 */

interface KineticCaptionProps {
  text: string;
  words: { word: string; startSec: number; endSec: number; highlighted: boolean; color?: string }[];
  startFrame: number;
  endFrame: number;
  style: "kinetic" | "subtitle";
  fontSize?: number;
}

function KineticCaption({
  text,
  words,
  startFrame,
  endFrame,
  style = "kinetic",
  fontSize = 80,
}: KineticCaptionProps) {
  const frame = useCurrentFrame();
  const { width, height } = useVideoConfig();
  const localFrame = frame - startFrame;
  const totalFrames = endFrame - startFrame;

  if (localFrame < 0 || localFrame > totalFrames) return null;

  // Entrance/exit timing
  const enterDuration = Math.round(0.4 * FPS); // 400ms entrance
  const exitDuration = Math.round(0.4 * FPS * 0.65); // 260ms exit
  const exitStart = totalFrames - exitDuration;

  // Overall visibility
  const isEntering = localFrame < enterDuration;
  const isExiting = localFrame > exitStart;
  const isVisible = !isEntering || localFrame >= 0;

  // Global scale (entrance bounce)
  let globalScale = 1;
  let globalOpacity = 1;

  if (isEntering) {
    const p = localFrame / enterDuration;
    globalScale = interpolate(p, [0, 0.7, 1], [0.85, 1.05, 1], { easing: EASE_IN_OUT });
    globalOpacity = interpolate(p, [0, 0.5], [0, 1], { easing: EASE_OUT });
  }

  if (isExiting) {
    const p = (localFrame - exitStart) / exitDuration;
    globalOpacity = interpolate(p, [0, 1], [1, 0], { easing: EASE_IN });
  }

  // Per-word animation with stagger
  const wordDelayFrames = Math.round(0.15 * FPS); // 150ms between words

  return (
    <AbsoluteFill
      style={{
        justifyContent: "center",
        alignItems: "center",
        paddingTop: style === "kinetic" ? height * HEADLINE_Y : height * CAPTION_Y,
        opacity: globalOpacity,
      }}
    >
      <div
        style={{
          display: "flex",
          flexWrap: "wrap",
          justifyContent: "center",
          gap: style === "kinetic" ? 12 : 4,
          transform: `scale(${globalScale})`,
        }}
      >
        {words.map((w, i) => {
          const wordStartFrame = startFrame + i * wordDelayFrames;
          const wordLocalFrame = frame - wordStartFrame;
          const wordDuration = Math.round(0.5 * FPS);

          if (wordLocalFrame < 0 || wordLocalFrame > totalFrames + wordDuration) {
            // Word not yet active or already done
            if (wordLocalFrame < 0) {
              return (
                <span
                  key={i}
                  style={{
                    fontFamily: tokens.fontFamily,
                    fontSize: style === "kinetic" ? fontSize : tokens.type.caption.size,
                    fontWeight: style === "kinetic" ? 700 : 400,
                    color: "transparent",
                    lineHeight: style === "kinetic" ? 1.1 : 1.4,
                    letterSpacing: style === "kinetic" ? "-0.02em" : "normal",
                  }}
                >
                  {w.word}
                </span>
              );
            }
            return null;
          }

          // Word entrance animation
          const wordEnterFrames = Math.round(0.25 * FPS);
          let wordScale = 1;
          let wordTranslateY = 0;
          let wordOpacity = 1;

          if (wordLocalFrame < wordEnterFrames) {
            const p = wordLocalFrame / wordEnterFrames;
            wordScale = interpolate(p, [0, 0.6, 1], [0.8, 1.08, 1], { easing: EASE_IN_OUT });
            wordTranslateY = interpolate(p, [0, 1], [20, 0], { easing: EASE_OUT });
            wordOpacity = interpolate(p, [0, 0.4], [0, 1], { easing: EASE_OUT });
          }

          // Word exit (during global exit)
          if (isExiting) {
            const p = (localFrame - exitStart) / exitDuration;
            wordOpacity = Math.min(wordOpacity, 1 - interpolate(p, [0, 0.5], [0, 1], { easing: EASE_IN }));
          }

          const isHighlighted = w.highlighted;
          const textColor = isHighlighted ? (w.color || "#FF4D2D") : "#FFFFFF";
          const textShadow = isHighlighted
            ? `0 0 20px ${w.color || "#FF4D2D"}80, 0 2px 8px rgba(0,0,0,0.8)`
            : "0 2px 8px rgba(0,0,0,0.8)";

          return (
            <span
              key={i}
              style={{
                fontFamily: tokens.fontFamily,
                fontSize: style === "kinetic" ? fontSize : tokens.type.caption.size,
                fontWeight: isHighlighted ? 700 : style === "kinetic" ? 600 : 400,
                color: textColor,
                lineHeight: style === "kinetic" ? 1.1 : 1.4,
                letterSpacing: style === "kinetic" ? "-0.02em" : "normal",
                textShadow,
                transform: `scale(${wordScale}) translateY(${wordTranslateY}px)`,
                opacity: wordOpacity,
                display: "inline-block",
                whiteSpace: "pre",
                transition: "none",
              }}
            >
              {w.word}
            </span>
          );
        })}
      </div>
    </AbsoluteFill>
  );
}

// ─── Animated Highlight Mark ────────────────────────────────────────────────
/**
 * Animated highlight bar behind a word/phrase.
 * Uses the reference-driven highlight events.
 */

interface HighlightMarkAnimatedProps {
  startFrame: number;
  duration: number;
  color: string;
  scale: number;
  animation: "slam" | "punch" | "fade" | "pop";
}

function HighlightMarkAnimated({
  startFrame,
  duration,
  color,
  scale,
  animation,
}: HighlightMarkAnimatedProps) {
  const frame = useCurrentFrame();
  const { height } = useVideoConfig();
  const localFrame = frame - startFrame;
  const totalFrames = Math.round((duration / 1000) * FPS);

  if (localFrame < 0 || localFrame > totalFrames) return null;

  const enterFrames = Math.round(0.2 * FPS);
  const exitFrames = Math.round(0.26 * FPS);
  const exitStart = totalFrames - exitFrames;

  let markScale = scale;
  let markOpacity = 1;

  // Entrance animation based on type
  if (localFrame < enterFrames) {
    const p = localFrame / enterFrames;
    switch (animation) {
      case "slam":
        markScale = interpolate(p, [0, 0.5, 1], [0.5, 1.15, scale], { easing: EASE_IN_OUT });
        break;
      case "punch":
        markScale = interpolate(p, [0, 0.5, 1], [0.8, scale * 1.1, scale], { easing: EASE_IN_OUT });
        break;
      case "pop":
        markScale = interpolate(p, [0, 0.5, 1], [0, 1.2, scale], { easing: EASE_OUT });
        break;
      default:
        markScale = interpolate(p, [0, 1], [0.5, scale], { easing: EASE_OUT });
    }
  }

  // Exit
  if (localFrame > exitStart) {
    const p = (localFrame - exitStart) / exitFrames;
    markOpacity = 1 - interpolate(p, [0, 1], [0, 1], { easing: EASE_IN });
  }

  return (
    <AbsoluteFill
      style={{
        justifyContent: "center",
        alignItems: "center",
        paddingTop: height * HEADLINE_Y,
        pointerEvents: "none",
      }}
    >
      {/* The highlight bar — positioned by the parent caption word */}
      <div
        style={{
          width: `${markScale * 100}%`,
          height: fontSize => fontSize * 0.15,
          backgroundColor: color,
          borderRadius: 4,
          opacity: markOpacity,
          marginTop: -4,
          boxShadow: `0 0 12px ${color}60`,
        }}
      />
    </AbsoluteFill>
  );
}

// ─── Camera Motion ──────────────────────────────────────────────────────────
/**
 * Reference-driven camera motion — applies zoom/punch/pull from blueprint.
 * Respects raw video's safe bounds.
 */

function ReferenceCameraMotion({ events }: { events: EditEvent[] }) {
  const frame = useCurrentFrame();
  const { width, height } = useVideoConfig();

  let scale = 1;
  let translateX = 0;
  let translateY = 0;

  for (const evt of events) {
    if (evt.category !== "camera") continue;

    const startFrame = Math.round(evt.timestamp * FPS);
    const totalFrames = Math.round((evt.duration / 1000) * FPS);
    const localFrame = frame - startFrame;

    if (localFrame < 0 || localFrame > totalFrames) continue;

    const progress = localFrame / totalFrames;
    const peakScale = (evt.params.peakScale as number) ?? 1.08;
    const startScale = (evt.params.startScale as number) ?? 1.0;
    const endScale = (evt.params.endScale as number) ?? 1.0;

    switch (evt.kind) {
      case "punch_in":
        scale = interpolate(progress, [0, 0.3, 0.7, 1], [startScale, peakScale, peakScale, endScale], { easing: EASE_IN_OUT });
        break;
      case "punch_out":
        scale = interpolate(progress, [0, 0.5, 1], [startScale, startScale, endScale], { easing: EASE_IN_OUT });
        break;
    }
  }

  return (
    <AbsoluteFill
      style={{
        transform: `scale(${scale}) translate(${translateX}px, ${translateY}px)`,
        transformOrigin: "center center",
      }}
    />
  );
}

// ─── SFX Trigger ────────────────────────────────────────────────────────────
/**
 * Triggers SFX at blueprint-specified timestamps.
 */

function ReferenceSfxTrigger({ events }: { events: EditEvent[] }) {
  // SFX are triggered via Remotion's <Audio> with Sequences
  // This component renders the Audio elements for SFX events
  const sfxEvents = events.filter((e) => e.category === "sfx");

  return (
    <>
      {sfxEvents.map((evt, i) => {
        const startFrame = Math.round(evt.timestamp * FPS);
        const durFrames = Math.max(1, Math.round((evt.duration / 1000) * FPS));
        const sfxPath = (evt.params.sfxPath as string) || "sfx/default.wav";

        return (
          <Sequence key={i} from={startFrame} durationInFrames={durFrames}>
            <Audio src={staticFile(sfxPath)} volume={0.4} />
          </Sequence>
        );
      })}
    </>
  );
}

