/**
 * manifest-generator.ts — generate the Remotion B-roll manifest and metadata files.
 *
 * Outputs:
 *   1. `src/videos/[name]/broll-manifest.ts` — Remotion-ready manifest array
 *   2. `work/[name]/broll/broll-metadata.json` — full provenance metadata
 *   3. `work/[name]/broll/BROLL-CUES.txt` — human-readable report
 */

