// ─── Manifest Generation ──────────────────────────────────────────────────────

/**
 * Convert a downloaded file's local path into the path Remotion's
 * `staticFile()` expects: relative to `public/`, forward slashes.
 *
 * Re-exported from asset-path.ts so the downloader (which writes the file) and
 * this generator (which names it in `file:`) share ONE definition of the
 * public/-relative form. Keeping a private copy here is exactly how a manifest
 * ends up pointing at a file the downloader never wrote.
 */
export { toStaticFilePath } from "./asset-path";

/**
 * Build a BrollManifestEntry for a segment.
 *
 * `file` is derived from the same asset-path helper the downloader uses to
 * place the clip, so the manifest always references the real filename.
 */
function buildManifestEntry(
  segment: VisualSegment,
  asset: DownloadedAsset,
  fps: number
): BrollManifestEntry {
  const durationFrames = segment.to - segment.from;
  // Zoom: start at 1.0, push in slightly. Faster pushes for shorter clips.
  const zoomAmount = Math.min(0.06, 0.3 / (durationFrames / 10));

  // Belt and braces: the downloader's localPath is authoritative, but assert
  // the filename really is the asset-path convention so a future downloader
  // change fails loudly here rather than silently writing a dangling reference.
  const expectedBasename = brollAssetFilename(asset.segmentId);
  const actualBasename = path.basename(asset.localPath);
  if (actualBasename !== expectedBasename) {
    throw new Error(
      `Manifest filename mismatch.\n  expected: ${expectedBasename}\n` +
        `  from asset: ${actualBasename}\n  localPath: ${asset.localPath}\n` +
        `  The downloader and manifest generator must agree on the filename.`
    );
  }

  return {
    phraseIndex: parseInt(segment.id.replace("seg-", ""), 10),
    file: toStaticFilePath(asset.localPath),
    from: segment.from,
    to: segment.to,
    zoomRange: [1.0, 1.0 + zoomAmount] as [number, number],
  };
}

/**
 * Generate Remotion broll-manifest.ts source code.
 */
export function generateRemotionManifest(
  segments: VisualSegment[],
  assets: DownloadedAsset[],
  fps: number
): string {
  const assetMap = new Map(assets.map((a) => [a.segmentId, a]));
  const brollSegments = segments
    .filter((s) => s.treatment === "broll")
    .filter((s) => assetMap.has(s.id));

  if (brollSegments.length === 0) {
    return `/**
 * broll-manifest.ts — B-roll manifest for this composition.
 *
 * No B-roll segments were generated for this video.
 * Add stock footage to public/projects/[name]/b-roll/ and update this file.
 *
 * Generated: ${new Date().toISOString()}
 */

export const BROLL_MANIFEST: {
  phraseIndex: number;
  file: string;
  from: number;
  to: number;
  zoomRange: [number, number];
}[] = [];
`;
  }

  const lines: string[] = [
    `/**
 * broll-manifest.ts — B-roll manifest for this composition.
 *
 * AUTO-GENERATED by broll-auto pipeline.
 * DO NOT EDIT MANUALLY — run \`npm run broll [project]\` to regenerate.
 *
 * Generated: ${new Date().toISOString()}
 * Segments: ${brollSegments.length}
 *
 * Provenance:`,
  ];

  for (const segment of brollSegments) {
    const asset = assetMap.get(segment.id);
    if (asset) {
      lines.push(` *   ${segment.id}: "${asset.creator}" (${asset.provider}) — ${asset.license}`);
      if (asset.attributionRequired && asset.attribution) {
        lines.push(` *     Attribution: ${asset.attribution}`);
      }
    }
  }

  lines.push(` */`);
  lines.push("");
  lines.push("export const BROLL_MANIFEST: {");
  lines.push("  phraseIndex: number;");
  lines.push("  file: string;");
  lines.push("  from: number;");
  lines.push("  to: number;");
  lines.push("  zoomRange: [number, number];");
  lines.push("}[] = [");

  for (const segment of brollSegments) {
    const asset = assetMap.get(segment.id);
    if (!asset) continue;

    const entry = buildManifestEntry(segment, asset, fps);
    lines.push("  {");
    lines.push(`    phraseIndex: ${entry.phraseIndex},`);
    lines.push(`    file: "${entry.file}",`);
    lines.push(`    from: ${entry.from},`);
    lines.push(`    to: ${entry.to},`);
    lines.push(`    zoomRange: [${entry.zoomRange[0].toFixed(2)}, ${entry.zoomRange[1].toFixed(2)}],`);
    lines.push("  },");
  }

  lines.push("];");
  lines.push("");

  return lines.join("\n");
}

/**
 * Generate a phrase-aligned B-roll manifest for the Premium composition.
 *
 * This is the function that safely writes the derived Premium manifest. It
 * accepts the PHRASES array from the Premium composition and uses it to
 * constrain every entry's from/to to phrase boundaries, preventing boundary-
 * crossing planner segments from activating B-roll during the wrong scene.
 *
 * The curated Premium manifest is NEVER written by this function — only the
 * `--manifest-path` destination (a separate file) is written. This function
 * is a pure read of planner+download output; it produces a derived manifest,
 * not a replacement of the curated one.
 *
 * Returns the manifest source code string; use `writeManifestFiles` or write
 * directly to the path configured in the pipeline config.
 */
export function generatePhraseAlignedManifest(
  phrases: PremiumPhrase[],
  plannerSegments: VisualSegment[],
  assets: DownloadedAsset[],
  fps: number
): string {
  const assetMap = new Map(assets.map((a) => [a.segmentId, a]));

  const aligned = buildPhraseAlignedManifest(phrases, plannerSegments);

  if (aligned.length === 0) {
    return `/**
 * broll-manifest-derived.ts — phrase-aligned B-roll manifest for
 * corporate-career-growth-amana-premium-916.
 *
 * No B-roll overlaps qualified (min 15 frames per phrase). All scenes
 * degrade to talking-head until clips land and a manifest entry is added.
 *
 * Generated: ${new Date().toISOString()}
 */

export const BROLL_MANIFEST: {
  phraseIndex: number;
  file: string;
  from: number;
  to: number;
  zoomRange: [number, number];
}[] = [];
`;
  }

  const lines: string[] = [
    `/**`,
    ` * broll-manifest-derived.ts — phrase-aligned B-roll manifest for`,
    ` * corporate-career-growth-amana-premium-916.`,
    ` *`,
    ` * AUTO-GENERATED by broll-auto pipeline.`,
    ` * Derived from planner segment output + Premium PHRASES alignment.`,
    ` * DO NOT EDIT MANUALLY — re-run the pipeline to regenerate.`,
    ` *`,
    ` * The curated manifest (broll-manifest.ts) is the authoritative source for`,
    ` * this composition. This file is a pipeline-derived working copy.`,
    ` *`,
    ` * Generated: ${new Date().toISOString()}`,
    ` * Phrase-aligned entries: ${aligned.length}`,
    ` */`,
    ``,
    `export const BROLL_MANIFEST: {`,
    `  phraseIndex: number;`,
    `  file: string;`,
    `  from: number;`,
    `  to: number;`,
    `  zoomRange: [number, number];`,
    `}[] = [`,
  ];

  for (const entry of aligned) {
    const asset = assetMap.get(entry.segmentId);
    if (!asset) {
      // Asset download was skipped or failed for this segment — skip this entry.
      // This is the correct behaviour; the composition degrades to talking-head
      // for this phrase until a clip lands.
      continue;
    }

    const phrase = phrases.find((p) => p.phraseIndex === entry.phraseIndex)!;
    const durationFrames = entry.to - entry.from;
    const zoomAmount = Math.min(0.06, 0.3 / (durationFrames / 10));

    lines.push("  {");
    lines.push(`    phraseIndex: ${entry.phraseIndex},`);
    lines.push(`    file: "${toStaticFilePath(asset.localPath)}",`);
    lines.push(`    from: ${entry.from},`);
    lines.push(`    to: ${entry.to},`);
    lines.push(
      `    zoomRange: [${(1.0).toFixed(2)}, ${(1.0 + zoomAmount).toFixed(2)}],`
    );
    lines.push("  },");
  }

  lines.push("];");
  lines.push("");

  return lines.join("\n");
}

/**
 * Generate human-readable metadata JSON.
 */
export function generateMetadata(
  segments: VisualSegment[],
  assets: DownloadedAsset[],
  validations: Array<{ assetId: string; passed: boolean; warnings: string[] }>,
  fps: number
): Record<string, unknown> {
  const assetMap = new Map(assets.map((a) => [a.id, a]));
  const validationMap = new Map(
    validations.map((v) => [v.assetId, v])
  );

  return {
    generatedAt: new Date().toISOString(),
    fps,
    totalSegments: segments.length,
    brollSegments: segments.filter((s) => s.treatment === "broll").length,
    assets: segments
      .filter((s) => s.treatment === "broll")
      .map((s) => {
        const asset = assetMap.get(s.id);
        const validation = validationMap.get(s.id);
        return {
          segmentId: s.id,
          transcript: s.transcriptText,
          searchQuery: s.searchQuery,
          provider: asset?.provider ?? "none",
          assetId: asset?.providerAssetId ?? "none",
          localPath: asset?.localPath ?? "none",
          creator: asset?.creator ?? "unknown",
          license: asset?.license ?? "unknown",
          attributionRequired: asset?.attributionRequired ?? false,
          attribution: asset?.attribution ?? null,
          fileSizeBytes: asset?.fileSizeBytes ?? 0,
          resolution: asset?.resolution ?? "unknown",
          durationSec: asset?.durationSec ?? 0,
          fileHash: asset?.fileHash ?? "none",
          downloadedAt: asset?.downloadedAt ?? "never",
          valid: validation?.passed ?? false,
          warnings: validation?.warnings ?? [],
        };
      }),
  };
}

// ─── Report Generation ───────────────────────────────────────────────────────

/**
 * Generate a human-readable B-roll report (BROLL-CUES.txt format).
 */
export function generateReport(
  segments: VisualSegment[],
  assets: DownloadedAsset[],
  validations: Array<{ assetId: string; passed: boolean; warnings: string[] }>,
  fps: number
): string {
  const lines: string[] = [];
  const assetMap = new Map(assets.map((a) => [a.segmentId, a]));
  const validationMap = new Map(
    validations.map((v) => [v.assetId, v])
  );

  lines.push("=".repeat(70));
  lines.push("B-ROLL AUTOMATION REPORT");
  lines.push("=".repeat(70));
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push(`FPS: ${fps}`);
  lines.push("");

  // Summary
  const brollSegs = segments.filter((s) => s.treatment === "broll");
  const thSegs = segments.filter((s) => s.treatment === "talking-head");
  const animSegs = segments.filter(
    (s) => s.treatment === "animated-graphic" || s.treatment === "highlight-only"
  );

  lines.push("SEGMENT SUMMARY");
  lines.push("-".repeat(40));
  lines.push(`  Total segments:      ${segments.length}`);
  lines.push(`  B-roll (downloaded):  ${brollSegs.length}`);
  lines.push(`  Talking-head:         ${thSegs.length}`);
  lines.push(`  Animated / highlight: ${animSegs.length}`);
  lines.push(`  Assets downloaded:    ${assets.length}`);
  lines.push(`  Assets failed:        ${validations.filter((v) => !v.passed).length}`);
  lines.push("");

  // Per-segment breakdown
  lines.push("SEGMENT BREAKDOWN");
  lines.push("-".repeat(70));

  for (const segment of segments) {
    const asset = assetMap.get(segment.id);
    const validation = validationMap.get(segment.id);
    const frameFrom = segment.from;
    const frameTo = segment.to;
    const timeFrom = (frameFrom / fps).toFixed(1);
    const timeTo = (frameTo / fps).toFixed(1);

    const statusIcon =
      segment.treatment === "broll" && asset && validation?.passed
        ? "✓"
        : segment.treatment === "broll" && !asset
          ? "✗"
          : segment.treatment === "talking-head"
            ? "●"
            : "○";

    lines.push("");
    lines.push(`[${statusIcon}] ${segment.id} | ${timeFrom}s–${timeTo}s | ${segment.treatment.toUpperCase()}`);
    lines.push(`    Text: "${segment.transcriptText.slice(0, 60)}${segment.transcriptText.length > 60 ? "..." : ""}"`);
    lines.push(`    Query: ${segment.searchQuery || "(none)"}`);

    if (asset) {
      lines.push(`    Provider: ${asset.provider} (${asset.creator})`);
      lines.push(`    File: ${asset.localPath} (${(asset.fileSizeBytes / 1024).toFixed(1)}KB)`);
      lines.push(`    License: ${asset.license} | Resolution: ${asset.resolution}`);
      if (asset.attributionRequired && asset.attribution) {
        lines.push(`    Attribution: ${asset.attribution}`);
      }
      if (validation?.warnings) {
        for (const warning of validation.warnings) {
          lines.push(`    ⚠ ${warning}`);
        }
      }
    } else if (segment.treatment === "broll") {
      lines.push("    ⚠ No asset downloaded");
    }

    if (segment.entities.length > 0) {
      lines.push(`    Entities: ${segment.entities.join(", ")}`);
    }
  }

  lines.push("");
  lines.push("=".repeat(70));
  lines.push("END OF REPORT");
  lines.push("=".repeat(70));

  return lines.join("\n");
}

// ─── File Writing ─────────────────────────────────────────────────────────────

export function writeManifestFiles(
  segments: VisualSegment[],
  assets: DownloadedAsset[],
  validations: Array<{ assetId: string; passed: boolean; warnings: string[] }>,
  fps: number,
  config: BrollPipelineConfig,
  /**
   * When supplied, the manifest is generated phrase-aligned: each entry's
   * from/to is clamped to the PHRASES phrase it serves. Omit to write the flat
   * (unconstrained) manifest.
   */
  phrases?: BrollPipelineConfig["phrases"]
): void {
  // Ensure output directories exist
  const manifestDir = path.dirname(config.output.manifestPath);
  const planDir = path.dirname(config.output.planPath);

  fs.mkdirSync(manifestDir, { recursive: true });
  fs.mkdirSync(planDir, { recursive: true });

  // 1. Write Remotion manifest.
  //
  // SAFETY: this writes ONLY to config.output.manifestPath — the destination the
  // caller explicitly chose via --manifest-path. The curated Premium manifest
  // is never written unless that path points at it, which the path guards in
  // config.ts already prevent for the protected production composition.
  //
  // When `phrases` is supplied the manifest is phrase-aligned, so a planner
  // segment that straddles a phrase boundary cannot activate B-roll during the
  // wrong scene. Without it, the flat manifest carries raw planner boundaries.
  const manifestCode = phrases
    ? generatePhraseAlignedManifest(phrases, segments, assets, fps)
    : generateRemotionManifest(segments, assets, fps);
  fs.writeFileSync(config.output.manifestPath, manifestCode);
  console.log(`  Manifest written: ${config.output.manifestPath}`);

  // 2. Write metadata JSON
  const metadata = generateMetadata(segments, assets, validations, fps);
  const metaPath = config.output.planPath.replace("plan.json", "broll-metadata.json");
  fs.writeFileSync(metaPath, JSON.stringify(metadata, null, 2));
  console.log(`  Metadata written: ${metaPath}`);

  // 3. Write report
  const report = generateReport(segments, assets, validations, fps);
  const reportPath = config.output.planPath.replace("plan.json", "BROLL-CUES.txt");
  fs.writeFileSync(reportPath, report);
  console.log(`  Report written: ${reportPath}`);
}
